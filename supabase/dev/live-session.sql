-- DEV ONLY. Makes today's timetable show a session that is live right now and one that opens soon, so the
-- Live / Check in states can be tried on the seeded student S1000001. Never run this on real data.
-- Run it in the Supabase SQL editor (or with execute_sql). Run it again any time to move the times to "now".
-- The reset block at the bottom puts things back.

-- 1) MAKE: S1000001's first class is live (started 15 minutes ago); the second opens for check in in about 30 minutes.
DO $$
DECLARE
  v_now timestamp := public.app_now();
  v_today date := v_now::date;
  v_live integer;
  v_soon integer;
  v_live_start time := date_trunc('minute', v_now - interval '15 minutes')::time;
  v_soon_start time := date_trunc('minute', v_now + interval '40 minutes')::time;
BEGIN
  SELECT class_schedule_id INTO v_live FROM public.enrollment WHERE user_id = 'S1000001' ORDER BY class_schedule_id LIMIT 1;
  SELECT class_schedule_id INTO v_soon FROM public.enrollment WHERE user_id = 'S1000001' ORDER BY class_schedule_id OFFSET 1 LIMIT 1;

  INSERT INTO public.class_session (class_schedule_id, session_date, status, override_start_time, override_end_time)
  VALUES (v_live, v_today, 'scheduled', v_live_start, (v_live_start + interval '105 minutes')::time)
  ON CONFLICT (class_schedule_id, session_date) DO UPDATE
    SET status = 'scheduled', override_start_time = EXCLUDED.override_start_time, override_end_time = EXCLUDED.override_end_time;

  INSERT INTO public.class_session (class_schedule_id, session_date, status, override_start_time, override_end_time)
  VALUES (v_soon, v_today, 'scheduled', v_soon_start, (v_soon_start + interval '120 minutes')::time)
  ON CONFLICT (class_schedule_id, session_date) DO UPDATE
    SET status = 'scheduled', override_start_time = EXCLUDED.override_start_time, override_end_time = EXCLUDED.override_end_time;
END $$;

